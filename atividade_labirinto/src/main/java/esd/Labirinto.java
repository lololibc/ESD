    private boolean podeAndar(int l, int c) {
        if (l < 0 || l >= mapa.length || c < 0 || c >= mapa[0].length) return false;
        return mapa[l][c] == ' ' || mapa[l][c] == 'T';
    }

    public boolean resolver() {
        int[][] direcoes = {{-1, 0}, {0, 1}, {1, 0}, {0, -1}};

        Stack<Posicao> pilha = new Stack<>(10);
        pilha.push(new Posicao(linhaInicial, colunaInicial));

        while (!pilha.isEmpty()) {
            Posicao atual = pilha.peek();

            if (atual.linha == linhaFinal && atual.coluna == colunaFinal) {
                return true;
            }

            boolean andou = false;
            for (int[] d : direcoes) {
                int l = atual.linha + d[0];
                int c = atual.coluna + d[1];
                if (podeAndar(l, c)) {
                    if (mapa[l][c] == ' ') mapa[l][c] = '.';
                    pilha.push(new Posicao(l, c));
                    andou = true;
                    break;
                }
            }

            if (!andou) {
                Posicao beco = pilha.pop();
                if (mapa[beco.linha][beco.coluna] == '.') mapa[beco.linha][beco.coluna] = 'x';
            }
        }
        return false;
    }
